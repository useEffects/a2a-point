#!/bin/bash

# Delete root node_modules and yarn.lock
echo "Deleting root node_modules..."
rm -rf node_modules

# Delete node_modules inside ./apps/*
echo "Deleting node_modules in ./apps/*..."
find ./apps -name "node_modules" -type d -prune -exec rm -rf '{}' +

# Delete node_modules inside ./packages/*
echo "Deleting node_modules in ./packages/*..."
find ./packages -name "node_modules" -type d -prune -exec rm -rf '{}' +

echo "Cleanup complete!"
